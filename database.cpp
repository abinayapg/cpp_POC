// database.cpp - plain-text .dat database (pipe separated, human editable)
//
//   CONFIG|maxOvers|spots|winPts|tiePts|nrPts
//   TEAM|name
//   MATCH|id|teamA|runsA|oversA|wktsA|teamB|runsB|oversB|wktsB|OK|NR
//   FIXTURE|teamA|teamB
#include "tournament.h"
#include <fstream>
#include <sstream>
#include <iostream>
#include <cstdlib>

static std::vector<std::string> split(const std::string& s, char d) {
    std::vector<std::string> out;
    std::string cur;
    std::stringstream ss(s);
    while (std::getline(ss, cur, d)) out.push_back(cur);
    return out;
}

int oversToBalls(const std::string& s) {
    if (s.empty()) return -1;
    size_t dot = s.find('.');
    int o = std::atoi(s.substr(0, dot).c_str());
    int b = 0;
    if (dot != std::string::npos && dot + 1 < s.size()) b = s[dot + 1] - '0';
    if (o < 0 || b < 0 || b > 5) return -1;
    return o * 6 + b;
}

std::string ballsToOvers(int balls) {
    return std::to_string(balls / 6) + "." + std::to_string(balls % 6);
}

int teamIndex(const Database& db, const std::string& name) {
    for (size_t i = 0; i < db.teams.size(); ++i)
        if (db.teams[i] == name) return (int)i;
    return -1;
}

bool loadDatabase(const std::string& path, Database& db) {
    std::ifstream in(path);
    if (!in) return false;
    db = Database();
    std::string line;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (line.empty() || line[0] == '#') continue;
        auto f = split(line, '|');
        if (f[0] == "CONFIG" && f.size() >= 6) {
            db.cfg.maxOvers = std::atoi(f[1].c_str());
            db.cfg.spots    = std::atoi(f[2].c_str());
            db.cfg.winPts   = std::atoi(f[3].c_str());
            db.cfg.tiePts   = std::atoi(f[4].c_str());
            db.cfg.nrPts    = std::atoi(f[5].c_str());
        } else if (f[0] == "TEAM" && f.size() >= 2) {
            db.teams.push_back(f[1]);
        } else if (f[0] == "MATCH" && f.size() >= 11) {
            Match m;
            m.id = std::atoi(f[1].c_str());
            m.a = f[2];
            m.ia.runs = std::atoi(f[3].c_str());
            m.ia.balls = oversToBalls(f[4]);
            m.ia.wkts = std::atoi(f[5].c_str());
            m.b = f[6];
            m.ib.runs = std::atoi(f[7].c_str());
            m.ib.balls = oversToBalls(f[8]);
            m.ib.wkts = std::atoi(f[9].c_str());
            m.noResult = (f[10] == "NR");
            if (teamIndex(db, m.a) < 0 || teamIndex(db, m.b) < 0) {
                std::cerr << "Skipping match " << m.id << ": unknown team\n";
                continue;
            }
            db.matches.push_back(m);
        } else if (f[0] == "FIXTURE" && f.size() >= 3) {
            if (teamIndex(db, f[1]) < 0 || teamIndex(db, f[2]) < 0) continue;
            db.fixtures.push_back({f[1], f[2]});
        }
    }
    return !db.teams.empty();
}

bool saveDatabase(const std::string& path, const Database& db) {
    std::ofstream out(path);
    if (!out) return false;
    out << "# Tournament database (auto-generated by the NRR engine)\n";
    out << "CONFIG|" << db.cfg.maxOvers << '|' << db.cfg.spots << '|' << db.cfg.winPts
        << '|' << db.cfg.tiePts << '|' << db.cfg.nrPts << "\n";
    for (auto& t : db.teams) out << "TEAM|" << t << "\n";
    for (auto& m : db.matches)
        out << "MATCH|" << m.id << '|' << m.a << '|' << m.ia.runs << '|' << ballsToOvers(m.ia.balls)
            << '|' << m.ia.wkts << '|' << m.b << '|' << m.ib.runs << '|' << ballsToOvers(m.ib.balls)
            << '|' << m.ib.wkts << '|' << (m.noResult ? "NR" : "OK") << "\n";
    for (auto& f : db.fixtures) out << "FIXTURE|" << f.a << '|' << f.b << "\n";
    return true;
}
